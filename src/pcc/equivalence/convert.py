"""Values across the Python/Dafny boundary for the equivalence checks (docs/plan.md, step 4).

Back-compiled Dafny uses its own runtime types: ``int`` and ``bool`` stay plain Python values, ``string`` and
``seq<T>`` become ``_dafny.Seq`` (of ``_dafny.CodePoint`` for strings), and Dafny tuples become plain Python tuples.
This module converts between those runtime values and plain Python values, guided by a type annotation object.

Supported annotations are ``int``, ``bool``, ``str``, ``list[X]`` (also ``typing.List[X]``), fixed ``tuple[X, ...]``
(also ``typing.Tuple``), homogeneous ``tuple[X, ...]`` and the empty ``tuple[()]``, nested freely. Anything else,
including ``dict``, ``set`` and ``float``, raises ``TypeError``, as does a value of the wrong shape. ``bool`` is not
accepted where ``int`` is expected and vice versa, so a converted ``int`` is never a ``bool``.

The module imports nothing from ``pcc`` and only the standard library at the top level. ``_dafny`` exists only next
to code ``dafny build`` generates, so it is imported inside the functions that need it.
"""

from __future__ import annotations

import typing
from typing import Any

__all__ = ["to_dafny", "to_python"]


def _runtime() -> Any:
    """The ``_dafny`` runtime generated next to back-compiled code. Imported lazily: it is only importable once a
    Dafny module has been built with ``dafny build --target:py``."""
    import _dafny  # type: ignore[import-not-found]  # generated by `dafny build`; ships without stubs

    return _dafny


def _single_arg(py_type: object, name: str) -> object:
    """The one element type of a ``list[X]`` annotation, or ``TypeError`` for a bare ``list``."""
    args = typing.get_args(py_type)
    if len(args) != 1:
        raise TypeError(f"unsupported {name} annotation without one element type: {py_type!r}")
    arg: object = args[0]
    return arg


def to_dafny(value: object, py_type: object) -> object:
    """Convert the plain Python ``value`` of type ``py_type`` into its Dafny runtime representation.

    Raises ``TypeError`` for an unsupported annotation or a value of the wrong shape.
    """
    if py_type is bool:
        if not isinstance(value, bool):
            raise TypeError(f"expected bool, got {type(value).__name__}")
        return value
    if py_type is int:
        if isinstance(value, bool) or not isinstance(value, int):
            raise TypeError(f"expected int, got {type(value).__name__}")
        return value
    if py_type is str:
        if not isinstance(value, str):
            raise TypeError(f"expected str, got {type(value).__name__}")
        dafny = _runtime()
        converted_str: object = dafny.Seq(map(dafny.CodePoint, value))
        return converted_str
    origin = typing.get_origin(py_type)
    if origin is list:
        item_type = _single_arg(py_type, "list")
        if not isinstance(value, list):
            raise TypeError(f"expected list, got {type(value).__name__}")
        dafny = _runtime()
        converted_list: object = dafny.Seq([to_dafny(item, item_type) for item in value])
        return converted_list
    if origin is tuple:
        if not isinstance(value, tuple):
            raise TypeError(f"expected tuple, got {type(value).__name__}")
        args = typing.get_args(py_type)
        if len(args) == 2 and args[1] is Ellipsis:
            converted_items: object = tuple(to_dafny(item, args[0]) for item in value)
            return converted_items
        if args == ((),):
            if value != ():
                raise TypeError(f"expected empty tuple, got {value!r}")
            return ()
        if len(args) != len(value):
            raise TypeError(f"expected tuple of length {len(args)}, got length {len(value)}")
        converted_fixed: object = tuple(to_dafny(item, item_type) for item, item_type in zip(value, args, strict=True))
        return converted_fixed
    raise TypeError(f"unsupported type annotation: {py_type!r}")


def to_python(value: object, py_type: object) -> object:
    """Convert the Dafny runtime ``value`` of type ``py_type`` back into a plain Python value.

    Raises ``TypeError`` for an unsupported annotation or a value of the wrong shape.
    """
    if py_type is bool:
        if not isinstance(value, bool):
            raise TypeError(f"expected Dafny bool, got {type(value).__name__}")
        return value
    if py_type is int:
        if isinstance(value, bool) or not isinstance(value, int):
            raise TypeError(f"expected Dafny int, got {type(value).__name__}")
        return value
    if py_type is str:
        dafny = _runtime()
        if not isinstance(value, dafny.Seq):
            raise TypeError(f"expected Dafny string, got {type(value).__name__}")
        for char in value.Elements:
            if not isinstance(char, str):
                raise TypeError(f"expected Dafny string, got element {char!r}")
        converted_str: object = "".join(value.Elements)
        return converted_str
    origin = typing.get_origin(py_type)
    if origin is list:
        item_type = _single_arg(py_type, "list")
        dafny = _runtime()
        if not isinstance(value, dafny.Seq):
            raise TypeError(f"expected Dafny seq, got {type(value).__name__}")
        converted_list: object = [to_python(item, item_type) for item in value.Elements]
        return converted_list
    if origin is tuple:
        if not isinstance(value, tuple):
            raise TypeError(f"expected Dafny tuple, got {type(value).__name__}")
        args = typing.get_args(py_type)
        if len(args) == 2 and args[1] is Ellipsis:
            converted_items: object = tuple(to_python(item, args[0]) for item in value)
            return converted_items
        if args == ((),):
            if value != ():
                raise TypeError(f"expected empty tuple, got {value!r}")
            return ()
        if len(args) != len(value):
            raise TypeError(f"expected tuple of length {len(args)}, got length {len(value)}")
        converted_fixed: object = tuple(to_python(item, item_type) for item, item_type in zip(value, args, strict=True))
        return converted_fixed
    raise TypeError(f"unsupported type annotation: {py_type!r}")
